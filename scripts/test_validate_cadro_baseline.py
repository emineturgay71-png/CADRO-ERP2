"""Regression tests for the source-controlled Phase 0 baseline checks.

Run with: python -m unittest discover -s scripts -p 'test_*.py' -v
"""

from __future__ import annotations

import copy
from pathlib import Path
import tempfile
import textwrap
import unittest
from unittest.mock import Mock, patch

import validate_cadro_baseline as baseline


LOCKFILE = '''# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"@framework/ui@link:../../frappe/ui":
  version "0.0.0"

"@babel/core@^7.24.4", "@babel/core@^7.25.0":
  version "7.29.7"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.29.7.tgz"
  integrity sha512-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA==

"reka-ui@2.10.1":
  version "2.10.1"
  resolved "https://registry.yarnpkg.com/reka-ui/-/reka-ui-2.10.1.tgz"
  integrity sha256-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=
'''


class YarnValidationTests(unittest.TestCase):
    def write_project(self, package: dict, lockfile: str = LOCKFILE):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        root = Path(directory.name)
        (root / "package.json").write_text(__import__("json").dumps(package), encoding="utf-8")
        (root / "yarn.lock").write_text(lockfile, encoding="utf-8")
        return root / "yarn.lock"

    def test_combined_selectors_local_link_and_resolution(self):
        manifest = self.write_project(
            {
                "dependencies": {"@babel/core": "^7.25.0"},
                "devDependencies": {"@babel/core": "^7.24.4"},
                "resolutions": {"reka-ui": "2.10.1"},
            }
        )
        self.assertIsNone(baseline.validate_local_project(manifest))

    def test_direct_missing_dependency_fails(self):
        manifest = self.write_project({"dependencies": {"is-not-locked": "^1.0.0"}})
        with self.assertRaisesRegex(baseline.BaselineValidationError, "lockfile lacks"):
            baseline.validate_local_project(manifest)

    def test_direct_integrity_cannot_borrow_another_block(self):
        bad = LOCKFILE.replace(
            '  integrity sha256-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=\n',
            "",
        )
        manifest = self.write_project({"dependencies": {"reka-ui": "2.10.1"}}, bad)
        with self.assertRaisesRegex(baseline.BaselineValidationError, "missing strong integrity"):
            baseline.validate_local_project(manifest)

    def test_malformed_digest_fails(self):
        bad = LOCKFILE.replace(
            "  integrity sha512-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA==",
            "  integrity sha512-!!NOT_VALID_BASE64!!",
        )
        manifest = self.write_project({"dependencies": {"@babel/core": "^7.24.4"}}, bad)
        with self.assertRaisesRegex(baseline.BaselineValidationError, "integrity"):
            baseline.validate_local_project(manifest)

    def test_missing_lock_version_fails(self):
        bad = LOCKFILE.replace('  version "2.10.1"\n', "")
        manifest = self.write_project({"dependencies": {"reka-ui": "2.10.1"}}, bad)
        with self.assertRaisesRegex(baseline.BaselineValidationError, "missing resolved version"):
            baseline.validate_local_project(manifest)


class ManifestValidationTests(unittest.TestCase):
    def document(self) -> dict:
        import json

        return json.loads((Path(__file__).parents[1] / "cadro.baseline.json").read_text(encoding="utf-8"))

    def test_current_manifest_is_valid_and_contains_upstream_baseline(self):
        with patch.object(baseline, "assert_local_ancestry") as ancestry:
            baseline.validate(Path(__file__).parents[1] / "cadro.baseline.json", verify_ancestry=False)
        # When verify_ancestry=False the function is never called
        ancestry.assert_not_called()

    def test_component_commit_must_match_upstream_source(self):
        document = self.document()
        document["components"][0]["commit"] = "0" * 40
        with patch.object(baseline, "assert_local_ancestry"), self.assertRaisesRegex(
            baseline.BaselineValidationError, "source_commit"
        ):
            baseline.validate(path=None, verify_ancestry=False, document=document)

    def test_short_sha_and_production_approval_are_rejected(self):
        for field, value in (("source_commit", "short"), ("production_approved", True)):
            with self.subTest(field=field):
                document = self.document()
                document["baseline"][field] = value
                with patch.object(baseline, "assert_local_ancestry"), self.assertRaises(
                    baseline.BaselineValidationError
                ):
                    baseline.validate(path=None, verify_ancestry=False, document=document)


if __name__ == "__main__":
    unittest.main()
